import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PERIOD_ID = "2026-2027-semester-1";
const FIXTURE_DIR = join(ROOT, "fixtures", PERIOD_ID);

function canonicalLabel(value) {
  return String(value ?? "")
    .replace(/\s+—\s+группа\s+№\s*\d+$/iu, "")
    .trim();
}

function optionalLabel(value) {
  return typeof value === "string" && value.trim().length > 0 ? value.trim() : null;
}

function groupsFromMask(maskHex, groupTable) {
  const mask = BigInt(`0x${maskHex}`);
  const groups = [];
  for (let index = 0; index < groupTable.length; index += 1) {
    if ((mask & (1n << BigInt(index))) !== 0n) groups.push(groupTable[index]);
  }
  return groups;
}

function addOption(
  target,
  groupId,
  selectionGroupId,
  selectionOptionId,
  disciplineLabel,
  selectionGroupLabel,
  selectionOptionLabel
) {
  let bySelection = target.get(groupId);
  if (!bySelection) {
    bySelection = new Map();
    target.set(groupId, bySelection);
  }

  let definition = bySelection.get(selectionGroupId);
  if (!definition) {
    definition = { label: null, options: new Map() };
    bySelection.set(selectionGroupId, definition);
  }

  const explicitGroupLabel = optionalLabel(selectionGroupLabel);
  if (explicitGroupLabel) {
    if (definition.label && definition.label !== explicitGroupLabel) {
      throw new Error(`conflicting selectionGroupLabel for ${selectionGroupId}: ${definition.label} / ${explicitGroupLabel}`);
    }
    definition.label = explicitGroupLabel;
  }

  const explicitOptionLabel = optionalLabel(selectionOptionLabel);
  const candidate = explicitOptionLabel ?? canonicalLabel(disciplineLabel) || selectionOptionId;
  const current = definition.options.get(selectionOptionId);
  if (current && explicitOptionLabel && current !== explicitOptionLabel) {
    throw new Error(`conflicting selectionOptionLabel for ${selectionGroupId}/${selectionOptionId}: ${current} / ${explicitOptionLabel}`);
  }
  if (!current || explicitOptionLabel || candidate.length < current.length) {
    definition.options.set(selectionOptionId, candidate);
  }
}

export async function buildElectiveCatalog() {
  const files = (await readdir(FIXTURE_DIR))
    .filter((name) => name.endsWith(".decisions.json"))
    .sort();
  const groups = new Map();

  for (const name of files) {
    const manifest = JSON.parse(await readFile(join(FIXTURE_DIR, name), "utf8"));
    const metadata = manifest.selectionMetadataByDisciplineIndex;
    if (!metadata || typeof metadata !== "object" || Array.isArray(metadata)) continue;
    if (!Array.isArray(manifest.groupTable) || !Array.isArray(manifest.disciplineTable)) continue;

    for (const decision of manifest.decisions ?? []) {
      if (!Array.isArray(decision) || decision.length < 6) continue;
      const groupMaskHex = decision[1];
      const disciplineIndex = decision[5];
      const selection = metadata[String(disciplineIndex)] ?? metadata[disciplineIndex];
      if (!selection) continue;
      if (typeof selection.selectionGroupId !== "string" || !selection.selectionGroupId) continue;
      if (typeof selection.selectionOptionId !== "string" || !selection.selectionOptionId) continue;
      const label = manifest.disciplineTable[disciplineIndex];
      for (const groupId of groupsFromMask(groupMaskHex, manifest.groupTable)) {
        addOption(
          groups,
          groupId,
          selection.selectionGroupId,
          selection.selectionOptionId,
          label,
          selection.selectionGroupLabel,
          selection.selectionOptionLabel
        );
      }
    }
  }

  const periodCatalog = {};
  for (const groupId of [...groups.keys()].sort((a, b) => a.localeCompare(b, "ru", { numeric: true }))) {
    const definitions = [];
    const bySelection = groups.get(groupId);
    for (const selectionGroupId of [...bySelection.keys()].sort()) {
      const definition = bySelection.get(selectionGroupId);
      const alternatives = [...definition.options.entries()]
        .sort((left, right) => left[1].localeCompare(right[1], "ru"))
        .map(([value, label]) => ({ value, label }));
      definitions.push({
        selectionId: selectionGroupId,
        label: definition.label ?? "Дисциплина по выбору",
        alternatives
      });
    }
    if (definitions.length) periodCatalog[groupId] = definitions;
  }

  return { [PERIOD_ID]: periodCatalog };
}

export function renderElectiveCatalog(catalog) {
  return `// Generated by tools/generate-elective-catalog.mjs. Do not edit by hand.\nwindow.KGMU_ELECTIVE_CATALOG = Object.freeze(${JSON.stringify(catalog, null, 2)});\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = process.argv[2];
  if (!output) {
    console.error("usage: node tools/generate-elective-catalog.mjs <output-path>");
    process.exitCode = 64;
  } else {
    await writeFile(resolve(output), renderElectiveCatalog(await buildElectiveCatalog()), "utf8");
  }
}
